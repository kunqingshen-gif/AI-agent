/** 信息型提问的识别：这些说法通常是在「问知识」，不是在「下指令」 */
const QUESTION_PATTERNS: RegExp[] = [
  /什么|啥意思|啥是/,
  /怎么(弄|办|用|查|交|申请|操作)?[？?]?$/,
  /怎么样|怎么办|怎么弄/,
  /如何|怎样/,
  /为什么|为何/,
  /多少(钱|岁|天|个月)?/,
  /多久|多长时间/,
  /能不能|可不可以|可以吗/,
  /是不是|有没有|要不要|需不需要/,
  /要带|需要带|带什么|材料|流程|条件|标准|区别/,
  /介绍|解释|说说|讲讲/,
  /[？?]\s*$/,
];

/**
 * 判断一句话是不是「提问」而不是「办事指令」。
 *
 * 关键取舍：像「我想问一下低保那个复核，今年还没弄呢」这种带「问」但实为办事的句子，
 * 不能被判成提问——否则演示主线会被答成一堆科普。所以判定不看「问」字，
 * 只看有没有真正的疑问特征，且不含明确的办事动词。
 */
export function looksLikeQuestion(text: string): boolean {
  const t = text.trim();
  if (!t) return false;
  const asking = QUESTION_PATTERNS.some((re) => re.test(t));
  if (!asking) return false;
  /*
   * 只有「明确的委托/指令」才按办事处理：我要办、帮我办、现在就办。
   * 「怎么申请」「要带什么」虽然含动词，但问的是方法，属于提问——
   * 这类问题答完之后给出 relatedTaskId，用户一句话就能转到办理。
   */
  const actionIntent = /我要办|帮我办|现在就办|给我办|直接办|帮我提交|我要申请|帮我申请/.test(t);
  if (actionIntent && !/什么|为什么|多少|多久|能不能|是不是|吗[？?]?$/.test(t)) return false;
  return true;
}

/** 按命中词数排序取前 N 条，作为离线答案与模型的事实依据 */
export function matchFaq(text: string, limit = 2): FaqEntry[] {
  const t = text.replace(/\s+/g, '');
  const scored = FAQ_ENTRIES.map((entry) => {
    let score = 0;
    for (const kw of entry.keywords) {
      if (kw.length >= 2 && t.includes(kw)) score += kw.length;
    }
    return { entry, score };
  })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((item) => item.entry);
}
